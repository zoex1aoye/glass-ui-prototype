/** 任一 locale 文案包含 query（小写）时为 true；用于侧栏搜索跨语言匹配 */
export function messageTextMatches(key: string, queryLower: string): boolean {
  if (!queryLower) return true
  for (const locale of ['zh', 'en'] as const) {
    const text = shellMessages[locale][key]
    if (text && text.toLowerCase().includes(queryLower)) return true
  }
  return false
}
